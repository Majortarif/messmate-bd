// Runs the MessMate BD database inside PGlite (in-memory Postgres 17):
//   shim → migrations 0001..0013 → seed.sql → tests/*.sql
// and writes supabase/setup.sql (all migrations except pg_cron, for pasting
// into the Supabase SQL editor in one go).
//
//   node run.mjs                 full run
//   node run.mjs --bundle-only   only regenerate supabase/setup.sql
//   node run.mjs --no-seed       migrations + tests, skip demo seed
import { PGlite } from '@electric-sql/pglite';
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const here = import.meta.dirname;
const supabaseDir = resolve(here, '..', '..');
const migrationsDir = join(supabaseDir, 'migrations');
const args = new Set(process.argv.slice(2));

const migrations = readdirSync(migrationsDir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const setupFiles = migrations.filter((f) => !f.includes('_cron'));

function bundle() {
  const header = [
    '-- =============================================================================',
    '-- MessMate BD · setup.sql (GENERATED by supabase/tests/pglite/run.mjs)',
    '-- All migrations except pg_cron, in order. Paste once into the Supabase SQL editor.',
    '-- Then run migrations/0013_cron.sql, and optionally seed.sql for demo data.',
    '-- =============================================================================',
    '',
  ].join('\n');
  const body = setupFiles
    .map((f) => `-- >>> ${f}\n${readFileSync(join(migrationsDir, f), 'utf8')}`)
    .join('\n\n');
  writeFileSync(join(supabaseDir, 'setup.sql'), header + body);
  console.log(`bundled ${setupFiles.length} migrations → supabase/setup.sql`);
}

function explain(file, sql, err) {
  const pos = Number(err.position);
  let where = '';
  if (pos > 0) {
    const before = sql.slice(0, pos);
    const line = before.split('\n').length;
    const lines = sql.split('\n');
    where = `\n  at line ${line}:\n    ${lines.slice(Math.max(0, line - 3), line + 1).join('\n    ')}`;
  }
  console.error(`\n✗ ${file}: ${err.message}${where}`);
  for (const k of ['detail', 'hint', 'where', 'internalQuery']) {
    if (err[k]) console.error(`  ${k}: ${err[k]}`);
  }
}

async function runFile(db, label, sql) {
  try {
    const results = await db.exec(sql);
    console.log(`✓ ${label}`);
    return results;
  } catch (err) {
    explain(label, sql, err);
    process.exit(1);
  }
}

bundle();
if (args.has('--bundle-only')) process.exit(0);

const db = await PGlite.create({ extensions: { pgcrypto } });
await db.exec(`set timezone = 'UTC'`);
await runFile(db, 'supabase-shim.sql', readFileSync(join(here, 'supabase-shim.sql'), 'utf8'));
await db.exec('create extension pgcrypto with schema extensions');

for (const f of migrations) {
  let sql = readFileSync(join(migrationsDir, f), 'utf8');
  // pg_cron is not available in PGlite; the shim provides cron.schedule().
  if (f.includes('_cron')) sql = sql.replace(/create extension if not exists pg_cron[^;]*;/i, '-- pg_cron: provided by shim');
  await runFile(db, f, sql);
}

if (!args.has('--no-seed')) {
  await runFile(db, 'seed.sql', readFileSync(join(supabaseDir, 'seed.sql'), 'utf8'));
  const counts = await db.query(`
    select (select count(*) from public.menus) menus,
           (select count(*) from public.meal_orders) orders,
           (select count(*) from public.ledger_entries) ledger,
           (select count(*) from public.monthly_closings) closings,
           (select count(*) from public.member_statements) statements,
           (select count(*) from public.listings) listings,
           (select count(*) from public.notifications) notifications`);
  console.log('  seed counts:', counts.rows[0]);
}

for (const f of ['rls_isolation.sql', 'functional.sql']) {
  const results = await runFile(db, `tests/${f}`, readFileSync(join(supabaseDir, 'tests', f), 'utf8'));
  const last = results.filter((r) => r.rows?.length).at(-1);
  console.log(`  → ${last ? Object.values(last.rows[0]).join(' ') : '(no result)'}`);
}

await db.close();
console.log('\nAll database checks passed.');
